drop policy if exists "download stats public read" on public.download_stats;
create policy "download stats public read" on public.download_stats for select using (true);

create or replace function public.register_download(p_patch_key text)
returns bigint language plpgsql security definer set search_path=public as $$
declare new_count bigint;
begin
  if p_patch_key is null or p_patch_key !~ '^[a-z0-9-]{1,80}$' then
    raise exception 'invalid patch key';
  end if;
  insert into public.download_stats(patch_key,download_count,updated_at)
  values(p_patch_key,1,now())
  on conflict(patch_key) do update
    set download_count=public.download_stats.download_count+1, updated_at=now()
  returning download_count into new_count;
  return new_count;
end; $$;
grant execute on function public.register_download(text) to anon, authenticated;

create or replace function public.get_download_count(p_patch_key text)
returns bigint language sql stable security definer set search_path=public as $$
  select coalesce((select download_count from public.download_stats where patch_key=p_patch_key),0);
$$;
grant execute on function public.get_download_count(text) to anon, authenticated;

create or replace function public.is_admin(uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=uid and role='admin');
$$;

-- Profiles
 drop policy if exists "profiles public read" on public.profiles;
create policy "profiles public read" on public.profiles for select using (true);
 drop policy if exists "profiles own update" on public.profiles;
create policy "profiles own update" on public.profiles for update using (auth.uid()=id) with check (auth.uid()=id);
revoke update on public.profiles from authenticated;
grant update(display_name, avatar_url) on public.profiles to authenticated;

-- Comments
 drop policy if exists "comments public read" on public.comments;
create policy "comments public read" on public.comments for select using (deleted_at is null or public.is_admin());
 drop policy if exists "comments user insert" on public.comments;
create policy "comments user insert" on public.comments for insert to authenticated with check (
  auth.uid()=user_id and exists(select 1 from public.profiles p where p.id=auth.uid() and not p.banned and (p.muted_until is null or p.muted_until <= now()))
);

-- Poll
 drop policy if exists "poll read" on public.poll_votes;
create policy "poll read" on public.poll_votes for select using (true);
 drop policy if exists "poll own insert" on public.poll_votes;
create policy "poll own insert" on public.poll_votes for insert to authenticated with check (auth.uid()=user_id and exists(select 1 from public.profiles p where p.id=auth.uid() and not p.banned));
 drop policy if exists "poll own update" on public.poll_votes;
create policy "poll own update" on public.poll_votes for update to authenticated using (auth.uid()=user_id) with check (auth.uid()=user_id and exists(select 1 from public.profiles p where p.id=auth.uid() and not p.banned));

-- Presence sadece güvenli RPC üzerinden
revoke all on public.presence from anon, authenticated;

create or replace function public.heartbeat_presence(p_session_id uuid)
returns integer language plpgsql security definer set search_path=public as $$
declare c integer;
begin
  insert into public.presence(session_id,user_id,last_seen) values(p_session_id,auth.uid(),now())
  on conflict(session_id) do update set user_id=auth.uid(), last_seen=now();
  select count(*) into c from public.presence where last_seen > now() - interval '2 minutes';
  return c;
end; $$;
grant execute on function public.heartbeat_presence(uuid) to anon, authenticated;

-- Admin RPC'leri
create or replace function public.admin_list_users(p_search text default '')
returns table(id uuid,email text,display_name text,role text,banned boolean,muted_until timestamptz,created_at timestamptz)
language plpgsql security definer set search_path=public,auth as $$
begin
  if not public.is_admin() then raise exception 'not authorized'; end if;
  return query select u.id,u.email,p.display_name,p.role,p.banned,p.muted_until,p.created_at
  from auth.users u join public.profiles p on p.id=u.id
  where coalesce(p_search,'')='' or p.display_name ilike '%'||p_search||'%' or u.email ilike '%'||p_search||'%'
  order by p.created_at desc limit 500;
end; $$;
grant execute on function public.admin_list_users(text) to authenticated;

create or replace function public.admin_list_comments(p_limit integer default 100)
returns table(id bigint,page text,body text,created_at timestamptz,user_id uuid,display_name text)
language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'not authorized'; end if;
  return query select c.id,c.page,c.body,c.created_at,c.user_id,p.display_name from public.comments c join public.profiles p on p.id=c.user_id where c.deleted_at is null order by c.created_at desc limit least(greatest(p_limit,1),500);
end; $$;
grant execute on function public.admin_list_comments(integer) to authenticated;

create or replace function public.admin_set_user_status(p_user_id uuid,p_banned boolean default null,p_muted_until timestamptz default null)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'not authorized'; end if;
  if p_user_id=auth.uid() then raise exception 'cannot moderate self'; end if;
  update public.profiles set banned=coalesce(p_banned,banned), muted_until=case when p_muted_until is null then muted_until else p_muted_until end where id=p_user_id and role<>'admin';
end; $$;
grant execute on function public.admin_set_user_status(uuid,boolean,timestamptz) to authenticated;

create or replace function public.admin_delete_comment(p_comment_id bigint)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_admin() then raise exception 'not authorized'; end if;
  update public.comments set deleted_at=now() where id=p_comment_id;
end; $$;
grant execute on function public.admin_delete_comment(bigint) to authenticated;

