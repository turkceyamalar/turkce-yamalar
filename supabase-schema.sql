create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Kullanıcı' check (char_length(display_name) between 2 and 24),
  avatar_url text,
  role text not null default 'user' check (role in ('user','admin')),
  banned boolean not null default false,
  muted_until timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  page text not null check (char_length(page) between 1 and 80),
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 800),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index if not exists comments_page_created_idx on public.comments(page, created_at desc);

create table if not exists public.poll_votes (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  choice text not null check (choice in ('Little Nightmares','Amenti','Throne and Liberty','Assassin’s Creed Valhalla','Diğer')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.presence (
  session_id uuid primary key,
  user_id uuid references public.profiles(id) on delete set null,
  last_seen timestamptz not null default now()
);
create index if not exists presence_last_seen_idx on public.presence(last_seen desc);

-- Yama indirme sayacı: kişisel bilgi tutmaz, sadece toplam sayıyı saklar.
create table if not exists public.download_stats (
  patch_key text primary key check (patch_key ~ '^[a-z0-9-]{1,80}$'),
  download_count bigint not null default 0 check (download_count >= 0),
  updated_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id, display_name)
  values(new.id, coalesce(nullif(new.raw_user_meta_data->>'display_name',''), split_part(new.email,'@',1), 'Kullanıcı'))
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

-- Eski kullanıcılar varsa profil oluştur
insert into public.profiles(id, display_name, created_at)
select id, coalesce(nullif(raw_user_meta_data->>'display_name',''), split_part(email,'@',1), 'Kullanıcı'), created_at
from auth.users
on conflict (id) do nothing;

